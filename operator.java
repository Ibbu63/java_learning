public class operator{
    public static void main(String[] args) {
        int a=10;
        int b=1;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);
        System.out.println(a>b);
        System.out.println(a<b);
        System.out.println(a==b);
        System.out.println(a>b? "a is greater" : "b is greater");
        System.out.println(a!=b);
        System.out.println(~a);
        System.out.println(a|b);
        System.out.println(a&b);
        System.out.println(++a);
        System.out.println(a++);
    }
}